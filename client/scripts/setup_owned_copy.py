#!/usr/bin/env python3
"""Validate an owner's local inputs, build FolkloreBoot and write launcher settings.

Experimental local flow: it never downloads, decrypts or starts the game. The
source repository, prefix, ELF and disc stay at their original paths.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib
import json
import os
import subprocess
import sys
from pathlib import Path

FORMAT = "folklore-owned-setup"
VERSION = 1
STATE_NAME = "setup-state.json"
SCRIPT_DIR = Path(__file__).resolve().parent
TOOLS = ("clang.exe", "clang++.exe", "cmake.exe", "ninja.exe", "SDL2.dll")
PROTECTED = ("disc", "elf", "dev_flash", "prefix", "shaders", "repo")
CHECKPOINT_STATES = ("prepared", "configured", "built")
# PowerShell treats all of these as single-quote characters inside literals.
PS_QUOTES = ("'", "\u2018", "\u2019", "\u201a", "\u201b")


class SetupError(Exception):
    """Actionable setup failure."""


def _module(name):
    for path in (SCRIPT_DIR, SCRIPT_DIR.parent / "launcher"):
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))
    return importlib.import_module(name)


def _norm(path):
    return os.path.normcase(os.path.realpath(path))


def _overlaps(a, b):
    a, b = _norm(a), _norm(b)
    return a == b or a.startswith(b.rstrip(os.sep) + os.sep) or b.startswith(a.rstrip(os.sep) + os.sep)


def _inside(root, path):
    return _norm(path).startswith(_norm(root).rstrip(os.sep) + os.sep)


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _plain_json(value):
    return json.loads(json.dumps(value, sort_keys=True, default=str))


def _load_json(path, what):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError) as exc:
        raise SetupError(f"cannot read {what} {path}: {exc}") from exc


def _check_plain(path):
    try:
        _module("build_owned_backup").plain_output(Path(path))
    except Exception as exc:
        raise SetupError(f"refusing linked or unsafe path {path}: {exc}") from exc


def _check_tree(workspace):
    _check_plain(workspace)
    for top, dirs, files in os.walk(workspace, followlinks=False):
        for name in dirs + files:
            _check_plain(Path(top) / name)


def _write(ws, path, text, encoding="utf-8"):
    path = Path(path)
    temp = path.with_name(path.name + ".tmp")
    for target in (path, temp):
        if not _inside(ws, target):
            raise SetupError(f"internal error: {target} is outside workspace {ws}")
        _check_plain(target)
    with open(temp, "w", encoding=encoding, newline="\n") as handle:
        handle.write(text)
    os.replace(temp, path)


def _mkdir(ws, path):
    if not _inside(ws, path):
        raise SetupError(f"internal error: {path} is outside workspace {ws}")
    _check_plain(path)
    path.mkdir(exist_ok=True)


def _save_state(ws, state):
    _write(ws, ws / STATE_NAME, json.dumps(state, indent=2, sort_keys=True) + "\n")


def _set_phase(ws, state, phase):
    state["phase"] = phase
    _save_state(ws, state)


def _snapshot(repo):
    roots = {"engine": repo / "engine", "client": repo / "client"}
    try:
        return _plain_json(_module("source_snapshot").snapshot_sources(roots))
    except Exception as exc:
        raise SetupError(f"cannot inventory sources under {repo}: {exc}") from exc


def ps_quote(value):
    value = str(value)
    if any(ch in value for ch in "\0\r\n"):
        raise SetupError(f"path contains control characters and cannot be quoted safely: {value!r}")
    for quote in PS_QUOTES:
        value = value.replace(quote, quote * 2)
    return "'" + value + "'"


def launch_script(bin_dir, entry, settings):
    command = [sys.executable, "-B", entry, "--config", settings]
    return "\n".join([
        "# Generated by setup_owned_copy.py. Starts the launcher only when you run it.",
        "$ErrorActionPreference = 'Stop'",
        f"$env:PATH = {ps_quote(bin_dir)} + [System.IO.Path]::PathSeparator + $env:PATH",
        "& " + " ".join(ps_quote(part) for part in command),
        "exit $LASTEXITCODE",
    ]) + "\n"


def _validate(args, repo, platform):
    if not platform.startswith("win"):
        raise SetupError("owner setup currently supports Windows only")
    paths = {}
    for key in ("disc", "elf", "dev_flash", "workspace", "prefix", "shaders"):
        value = getattr(args, key)
        if not Path(value).is_absolute():
            raise SetupError(f"--{key.replace('_', '-')} must be an absolute path: {value}")
        paths[key] = Path(os.path.abspath(value))
    paths["repo"] = repo = Path(os.path.abspath(repo))
    if not (repo / "engine").is_dir() or not (repo / "client").is_dir():
        raise SetupError(f"source repository {repo} must contain engine/ and client/")
    if not paths["disc"].is_dir():
        raise SetupError(f"--disc must be the extracted disc folder: {paths['disc']}")
    if not paths["elf"].is_file():
        raise SetupError(f"--elf must be an existing file: {paths['elf']}")
    dev = paths["dev_flash"]
    if not dev.is_dir() or not any(dev.iterdir()):
        raise SetupError(f"--dev-flash must be a non-empty dev_flash folder: {dev}")
    bin_dir = paths["prefix"] / "bin"
    missing = [tool for tool in TOOLS if not (bin_dir / tool).is_file()]
    if missing:
        raise SetupError(f"{bin_dir} lacks {', '.join(missing)}; install the MSYS2 clang64 dependencies")
    manifest_path = paths["shaders"] / "manifest.json"
    manifest = _load_json(manifest_path, "shader manifest")
    if not isinstance(manifest, dict) or manifest.get("passed") is not True:
        raise SetupError(f"{manifest_path} must record passed: true from the CACAO shader builder")
    headers = paths["shaders"] / "PrecompiledShadersSPIRV"
    if not headers.is_dir() or not any(headers.iterdir()):
        raise SetupError(f"{headers} must be a non-empty shader header folder")
    ws = paths["workspace"]
    for key in PROTECTED:
        if _overlaps(ws, paths[key]):
            raise SetupError(f"--workspace {ws} overlaps {key} {paths[key]}; choose a separate folder")
    if not ws.parent.is_dir():
        raise SetupError(f"workspace parent {ws.parent} does not exist; create it first")
    # Guest filesystem buffers impose a limit even when Windows accepts the path.
    # Read the same source declaration that will be bound to the resulting build.
    core = _module("launcher_core")
    capability_path = repo / "client" / "native" / "launcher-capabilities.json"
    try:
        caps = core.Capabilities(**core.parse_capability_record(capability_path.read_bytes(), bridge_built=False))
        core.check_profile_length(ws / "profile" / "dev_hdd0", caps)
    except (OSError, ValueError) as exc:
        raise SetupError(f"cannot use this installation folder: {exc} Choose a shorter new folder before building.") from exc
    _check_plain(ws)
    if args.resume:
        if not ws.is_dir():
            raise SetupError(f"--resume needs an existing workspace folder: {ws}")
        _check_tree(ws)
    elif os.path.lexists(ws):
        raise SetupError(f"workspace {ws} already exists; choose a new folder or pass --resume")
    return paths


def _open_state(ws, bindings, identity, snapshot, resume):
    path = ws / STATE_NAME
    if resume:
        state = _load_json(path, "setup receipt")
        if not isinstance(state, dict) or state.get("format") != FORMAT or state.get("version") != VERSION:
            raise SetupError(f"{path} is not a setup receipt from this tool")
        for key, current in (("bindings", bindings), ("identity", identity), ("source_snapshot", snapshot)):
            if state.get(key) != current:
                raise SetupError(f"--resume {key} do not match {path}; restore the original inputs or use a new workspace")
        if not isinstance(state.get("commands"), list):
            raise SetupError(f"{path} has no command receipts; use a new workspace")
        state.pop("error", None)
        return state
    ws.mkdir()
    state = {"format": FORMAT, "version": VERSION, "bindings": bindings, "identity": identity,
             "source_snapshot": snapshot, "phase": "validated", "commands": [], "runtime_tested": False}
    _save_state(ws, state)
    return state


def _run(ws, state, name, cmd, env, run):
    logs = ws / "logs"
    _mkdir(ws, logs)
    index = len(state["commands"]) + 1
    while os.path.lexists(log := logs / f"{index:03d}-{name}.log"):
        index += 1
    _check_plain(log)
    with open(log, "x", encoding="utf-8") as handle:
        try:
            code = run(cmd, cwd=str(ws), env=env, stdin=subprocess.DEVNULL, stdout=handle,
                       stderr=subprocess.STDOUT, shell=False, check=False).returncode
        except OSError as exc:
            handle.write(f"could not start: {exc}\n")
            code = None
    state["commands"].append({"name": name, "args": cmd, "exit_code": code, "log": str(log)})
    _save_state(ws, state)
    if code != 0:
        status = "could not start" if code is None else f"exited with code {code}"
        raise SetupError(f"{name} {status}; see {log}, fix the cause and rerun with --resume")


def _verify_metadata(metadata):
    receipt = metadata / "receipt.json"
    hint = f"delete {metadata} and rerun with --resume to regenerate it"
    data = _load_json(receipt, "metadata receipt") if receipt.is_file() else None
    files = data.get("files") if isinstance(data, dict) else None
    if not isinstance(data, dict) or data.get("state") != "verified" or not isinstance(files, dict) or not files:
        raise SetupError(f"{receipt} is missing or not a verified metadata receipt; {hint}")
    for rel, digest in files.items():
        target = metadata / str(rel)
        if not _inside(metadata, target) or not target.is_file():
            raise SetupError(f"metadata file {target} listed in {receipt} is missing; {hint}")
        _check_plain(target)
        if _sha256(target) != digest:
            raise SetupError(f"metadata file {target} does not match {receipt}; {hint}")


def _verify_build(checkpoint, build, snapshot):
    binary = build / "native-build" / "FolkloreBoot.exe"
    if not isinstance(checkpoint, dict) or checkpoint.get("state") != "built":
        raise SetupError(f"builder exited 0 but {build / 'checkpoint.json'} is not in state 'built'; rerun with --resume")
    recorded = checkpoint.get("binary")
    if not isinstance(recorded, str) or _norm(recorded) != _norm(binary):
        raise SetupError(f"checkpoint binary {recorded!r} is not {binary}; refusing an unexpected executable")
    _check_plain(binary)
    if not binary.is_file() or _sha256(binary) != checkpoint.get("binary_sha256"):
        raise SetupError(f"{binary} is missing or its SHA-256 differs from the checkpoint; rerun with --resume")
    if _plain_json(checkpoint.get("build_source_snapshot")) != snapshot:
        raise SetupError("checkpoint build_source_snapshot differs from the current engine/client sources; rerun with --resume")
    return binary, checkpoint["binary_sha256"]


def _write_settings(ws, paths, binary, state):
    settings = ws / "settings.json"
    expected = dict(binary=str(binary), elf=str(paths["elf"]), disc=str(paths["disc"]),
                    hdd0=str(ws / "profile" / "dev_hdd0"), dev_flash=str(paths["dev_flash"]))
    core = _module("launcher_core")
    reused = os.path.lexists(settings)
    try:
        config = _load_json(settings, "launcher settings") if reused else copy.deepcopy(core.default_config())
        if reused:
            core.validate_config(config)
            if any(_norm(config["paths"].get(key, "")) != _norm(value) for key, value in expected.items()):
                raise SetupError("existing launcher settings target different inputs; preserve them and choose a new workspace")
        else:
            config["paths"].update(expected)
        # The launcher's path checks require an existing, separate save folder.
        # mkdir(exist_ok=True) preserves all existing save files on resume.
        _mkdir(ws, ws / "profile")
        _mkdir(ws, ws / "profile" / "dev_hdd0")
        core.validate_config(config, check_paths=True)
    except (ValueError, KeyError, TypeError, AttributeError) as exc:
        raise SetupError(f"launcher settings are invalid: {exc}; existing settings were preserved") from exc
    if not reused:
        _write(ws, settings, json.dumps(config, indent=2, default=str) + "\n")
    state["settings_reused"] = reused
    return settings


def _install(args, paths, state, snapshot, run):
    ws, repo, bin_dir = paths["workspace"], paths["repo"], paths["prefix"] / "bin"
    scripts, support = repo / "client" / "scripts", repo / "client" / "build-support"
    tmp = ws / "tmp"
    _mkdir(ws, tmp)
    env = dict(os.environ)
    env.update(TEMP=str(tmp), TMP=str(tmp), PYTHONDONTWRITEBYTECODE="1",
               PATH=str(bin_dir) + os.pathsep + env.get("PATH", ""))
    metadata = ws / "metadata"
    if not os.path.lexists(metadata):
        _run(ws, state, "prepare-metadata", [
            sys.executable, "-B", str(scripts / "prepare_owned_metadata.py"), "--elf", str(paths["elf"]),
            "--sdk", str(repo / "engine"), "--output", str(metadata)], env, run)
    _verify_metadata(metadata)
    _set_phase(ws, state, "metadata-verified")
    build = ws / "build"
    checkpoint_path = build / "checkpoint.json"
    cmd = [sys.executable, "-B", str(scripts / "build_owned_backup.py"), "--elf", str(paths["elf"]),
           "--sdk", str(repo / "engine"), "--metadata", str(metadata),
           "--ppu-manifest", str(support / "ppu-acceptance.json"),
           "--spu-manifest", str(support / "spu-acceptance.json"), "--toolchain", str(bin_dir),
           "--prefix", str(paths["prefix"]), "--shader-dir", str(paths["shaders"]),
           "--source", str(repo / "client"), "--output", str(build), "--jobs", str(args.jobs)]
    if args.prepare_only:
        cmd.append("--prepare-only")
    if checkpoint_path.is_file():
        cmd.append("--resume")
    _run(ws, state, "build", cmd, env, run)
    _check_plain(checkpoint_path)
    checkpoint = _load_json(checkpoint_path, "build checkpoint")
    if args.prepare_only:
        if not isinstance(checkpoint, dict) or checkpoint.get("state") not in CHECKPOINT_STATES:
            raise SetupError(f"builder exited 0 but {checkpoint_path} has no prepared state; rerun with --resume")
        _set_phase(ws, state, "prepared")
        return {"phase": "prepared", "binary": None, "launcher": None, "settings": None, "runtime_tested": False}
    binary, digest = _verify_build(checkpoint, build, snapshot)
    if _snapshot(repo) != snapshot:
        raise SetupError("engine/client sources changed during the build; restore them and rerun with --resume")
    state.update(binary=str(binary), binary_sha256=digest)
    _set_phase(ws, state, "built")
    settings = _write_settings(ws, paths, binary, state)
    launcher = ws / "Launch.ps1"
    entry = repo / "client" / "launcher" / "portable_entry.py"
    _write(ws, launcher, launch_script(bin_dir, entry, settings), encoding="utf-8-sig")
    state.update(settings=str(settings), launcher=str(launcher))
    _set_phase(ws, state, "installed-local-untested")
    return {"phase": state["phase"], "binary": str(binary), "launcher": str(launcher),
            "settings": str(settings), "runtime_tested": False}


def _jobs(text):
    value = int(text)
    if not 1 <= value <= 32:
        raise argparse.ArgumentTypeError("--jobs must be between 1 and 32")
    return value


def _parser():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for name in ("--disc", "--elf", "--dev-flash", "--workspace", "--prefix", "--shaders"):
        parser.add_argument(name, required=True)
    parser.add_argument("--jobs", type=_jobs, default=2)
    parser.add_argument("--prepare-only", action="store_true")
    parser.add_argument("--resume", action="store_true")
    return parser


def main(argv=None, *, repo=None, platform=None, run=subprocess.run):
    args = _parser().parse_args(argv)
    repo = Path(repo) if repo is not None else Path(__file__).resolve().parents[2]
    state = workspace = None
    try:
        paths = _validate(args, repo, platform or sys.platform)
        workspace = paths["workspace"]
        try:
            identity = _module("backup_validation").validate_backup(paths["disc"], paths["elf"])
        except Exception as exc:
            raise SetupError(f"disc/ELF validation failed: {exc}") from exc
        snapshot = _snapshot(paths["repo"])
        bindings = {key: str(value) for key, value in paths.items()}
        state = _open_state(workspace, bindings, _plain_json(identity), snapshot, args.resume)
        result = _install(args, paths, state, snapshot, run)
    except (SetupError, OSError) as exc:
        if state is not None:
            state["error"] = str(exc)
            try:
                _save_state(workspace, state)
            except (SetupError, OSError):
                pass
        print(f"setup_owned_copy: error: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
